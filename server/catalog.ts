const STATIC_TIMESTAMP = '2026-01-01T00:00:00.000Z';

function makeRefEvent(
  id: string,
  title: string,
  summary: string,
  category: IntelEvent['category'],
  lat: number,
  lon: number,
  country: string,
  countryCode: string,
  region: string,
  org: string,
  url: string,
  tags: string[]
): IntelEvent {
  return {
    id,
    title,
    summary,
    category,
    severity: 'info',
    nature: 'public_reference',
    lat,
    lon,
    geoPrecision: 'exact',
    country,
    countryCode,
    region,
    publishedAt: STATIC_TIMESTAMP,
    collectedAt: STATIC_TIMESTAMP,
    updatedAt: STATIC_TIMESTAMP,
    sources: [
      {
        id: `ref-${id}`,
        organization: org,
        title,
        url,
        publishedAt: STATIC_TIMESTAMP,
        collectedAt: STATIC_TIMESTAMP,
        language: 'en',
        nature: 'public_reference',
        snippet: summary,
      },
    ],
    independentOrgCount: 1,
    confidence: 'high',
    confidenceExplanation: `Verified static geographic reference from ${org}. Represents fixed infrastructure location, not a live incident.`,
    tags: [...tags, 'static-reference'],
  };
}

